def gen_docs(write: bool = False, prose: bool = False) -> str:
    """The README's map table, regenerated from the workspace itself.

    DETERMINISTIC — descriptions come from each package's pyproject, the
    rows from the members list. package_doc (the stub) is the served-lane
    upgrade for paragraph prose; the table never needed a model, which is
    why it could never drift once this existed.
    """
    import re as _re
    import tomllib

    rows = []
    for member, pkg in PACKAGES.items():
        py = ROOT / member.split("/src")[0].split("/montology")[0] / "pyproject.toml"
        py = ROOT / pathlib_parts(member) / "pyproject.toml"
        meta = tomllib.loads(py.read_text())["project"]
        import_name = pkg.rsplit("/", 1)[-1]
        rows.append(f"| `{member}/` | `{import_name}` | {meta['description']} |")
    table = ("| package | import | what it is |\n|---|---|---|\n"
             + "\n".join(rows)
             + "\n| `skills/` | — | Agent Skills: how to use all of the above, in the agent's language. |")

    readme = (ROOT / "README.md").read_text()
    new = _re.sub(
        r"\| package \| import \| what it is \|.*?\| `skills/` \| — \|[^\n]*\|",
        table.replace("\\", "\\\\"), readme, count=1, flags=_re.S,
    )
    report = []
    if new == readme:
        report.append("README map table already current")
    elif write:
        (ROOT / "README.md").write_text(new)
        report.append(f"README map table regenerated ({len(rows)} packages)")
    else:
        return table

    # THE PROSE LAYER: package_doc paragraphs into docs/PACKAGES.md when a
    # model is present (its only caller — no more orphan stub). No backend
    # -> stated skip; the table above never needed a model and never waits.
    if prose:
        session = gen_session()
        if isinstance(session, str):
            report.append("prose skipped: no model backend (the map table is deterministic and done)")
        else:
            from .stubs import package_doc

            paras = []
            for member, pkg in PACKAGES.items():
                meta = tomllib.loads((ROOT / pathlib_parts(member) / "pyproject.toml").read_text())["project"]
                try:
                    para = str(package_doc(session, package_surface=package_surface(pkg),
                                           pyproject_description=meta["description"])).strip()
                except Exception as e:  # noqa: BLE001 — one bad paragraph, not a dead doc
                    para = f"({type(e).__name__} — paragraph not generated)"
                paras.append(f"## {member}\n\n{para}")
            doc = ("<!-- GENERATED by monty gen (package_doc) — regenerate with "
                   "`monty gen docs --prose --write` -->\n\n# The packages\n\n"
                   + "\n\n".join(paras) + "\n")
            if write:
                (ROOT / "docs").mkdir(exist_ok=True)
                (ROOT / "docs" / "PACKAGES.md").write_text(doc)
                report.append(f"docs/PACKAGES.md written ({len(paras)} paragraphs)")
            else:
                report.append(doc[:2000])
    return "\n".join(report)


def pathlib_parts(member: str):
    from pathlib import PurePosixPath

    return PurePosixPath(member)


def lint() -> list[str]:
    """Deterministic, model-free. In `just check`.

    Structural laws over every skill on disk; grounding laws over the
    generated ones; and the no-prompt ban over this package itself.
    """
    report: list[str] = []
    failed = False

    from .laws import provenance_current

    for skill in skills_inventory():
        text = (ROOT / skill["path"]).read_text()
        laws = STRUCTURAL + (GROUNDING if skill["generated"] else ())
        # THE DRIFT GATE, the promise made in CLAUDE.md kept here: a GENERATED
        # skill is re-checked against the package's CURRENT AST on every lint —
        # a renamed tool or changed surface fails the build with the
        # regenerate repair, which is what forces the update.
        if skill["generated"] and skill["name"] in SKILL_PACKAGES:
            surface = package_surface(SKILL_PACKAGES[skill["name"]])
            laws = laws + (tools_exist(surface), provenance_current(fingerprint(surface)))
        for f in _check(text, laws):
            failed = True
            report.append(f"FAIL {skill['path']}: {f}")

    # the no-prompt ban, enforced where it could be broken
    import re

    for py in sorted((ROOT / ".monty" / "gen" / "src" / "montology_gen").glob("*.py")):
        for bad in re.findall(r'"(You are[^"]{0,60}|Please [^"]{0,60})"', py.read_text()):
            failed = True
            report.append(f"FAIL {py.name}: prompt-shaped string {bad!r} — specs, not prompts")

    report.append("lint: " + ("FAILED" if failed else
                              f"ok — {len(skills_inventory())} skills, no prompt-shaped strings"))
    return report
