from .laws import GROUNDING, STRUCTURAL, Law, substance, tools_exist, word_laws

HOUSE_RULES = [
    "Numbers come from tools, never from memory — if a tool did not return it "
    "in this session, do not state it.",
    "Categories are looked up, not guessed; taxonomy_search output is a category, "
    "a hunch is not.",
    "When a key or dependency is missing, relay the repair the tool gives — do not "
    "improvise workarounds.",
]


def _check(text: str, laws: tuple[Law, ...]) -> list[str]:
    return [f"{law.name}: {why}" for law in laws if (why := law.check(text))]


def _record(task: str, target: str, model: str, outcome: str, failures: list[str]) -> None:
    """THE ASSAY. Every generation outcome lands in the warehouse, so 'which
    model earns which tier' is a SQL question over measured rows, not a
    debate: monty sql "SELECT model, outcome, count(*) FROM gen_runs
    GROUP BY 1, 2". Best-effort — a run must never die on its bookkeeping."""
    try:
        from montology_warehouse import connect

        conn = connect()
        conn.execute(
            "CREATE TABLE IF NOT EXISTS gen_runs ("
            "ran_at TIMESTAMP, task VARCHAR, target VARCHAR, "
            "model VARCHAR, outcome VARCHAR, laws_failed VARCHAR[])"
        )
        conn.execute(
            "INSERT INTO gen_runs VALUES (now(),?,?,?,?,?)",
            [task, target, model, outcome, [f.split(":")[0] for f in failures]],
        )
        conn.close()
    except Exception as e:  # noqa: BLE001
        print(f"[gen assay not recorded] {e}", flush=True)


def _model_of(session) -> str:
    got = getattr(getattr(session, "backend", None), "model_id", None)
    return str(got) if got else "unknown"


def _provenance(stub: str, session, print_hash: str) -> str:
    model = getattr(getattr(session, "backend", None), "model_id", "unknown")
    return (f"<!-- GENERATED by monty gen ({stub}) — model={model} "
            f"date={datetime.now(UTC).date()} instruments=sha256:{print_hash} — "
            f"edit the instruments (code, data), not this file -->")


def _piecewise_already_refused(model: str) -> bool:
    """THE ASSAY IS THE MEMORY. A model id with a piecewise refusal on record
    and no acceptance since is skipped — steady state costs nothing, and a
    NEW model id gets its shot automatically (auto-promotion intact). Force a
    re-attempt with --try-local."""
    try:
        from montology_warehouse import connect

        conn = connect()
        row = conn.execute(
            "SELECT outcome FROM gen_runs WHERE task='skill' AND model=? "
            "ORDER BY ran_at DESC LIMIT 1", [f"{model}+piecewise"],
        ).fetchone()
        conn.close()
        return bool(row) and row[0] in ("refused", "errored")
    except Exception:  # noqa: BLE001 — no warehouse, no memory: attempt
        return False


def gen_skill(skill_name: str, write: bool = False, try_local: bool = False) -> str:
    """Generate (or regenerate) one package's skill from its instruments.

    TWO DRAFTERS, ONE CONTRACT. With a served endpoint (MONTOLOGY_MODEL_URL)
    the stubs draft autonomously — on a server, never on this machine.
    Otherwise the HOST AGENT is the drafter: the marketer is already working
    through a frontier model, so gen emits the grounded task (instruments,
    spec, laws) for it to fulfill, and `gen lint` in `just check` enforces
    the result either way. Locally, the 292 MB atomic tier is the only
    inference montology ever runs.
    """
    pkg = SKILL_PACKAGES.get(skill_name)
    if pkg is None:
        return f"no package mapping for {skill_name!r}. Known: {', '.join(SKILL_PACKAGES)}"

    session = gen_session()
    if isinstance(session, str):
        # THE PIECEWISE EXPERIMENT: before handing off, let the atomic tier
        # try the body DECOMPOSED — structure built by code (frontmatter and
        # sections cannot fail to parse), prose filled slot by slot at the
        # size the 292 MB model already passes. The laws judge the assembled
        # whole; a refusal falls through to the handoff and the assay records
        # both, so 'can the 292 do bodies' stays a measured question.
        from ._session import tiny_session

        tiny = tiny_session()
        if tiny is not None and not try_local and _piecewise_already_refused(_model_of(tiny)):
            _record("skill", skill_name, "host-agent", "handoff", [])
            return (
                f"(piecewise skipped: {_model_of(tiny)} has a refusal on record — "
                "`--try-local` re-attempts)\n\n" + _handoff(skill_name, pkg)
            )
        if tiny is not None:
            # A model that cannot even produce structured output is an assay
            # outcome (errored), never a traceback — observed live: a
            # thinking-mode 0.8B answered the stub with empty output and the
            # ValidationError escaped to the user.
            try:
                text, failures = _assemble_piecewise(tiny, skill_name, pkg)
            except Exception as e:  # noqa: BLE001
                _record("skill", skill_name, f"{_model_of(tiny)}+piecewise", "errored",
                        [f"{type(e).__name__}"])
                _record("skill", skill_name, "host-agent", "handoff", [])
                return (
                    f"(piecewise errored on {_model_of(tiny)}: {type(e).__name__} — "
                    "recorded)\n\n" + _handoff(skill_name, pkg)
                )
            if not failures:
                _record("skill", skill_name, f"{_model_of(tiny)}+piecewise", "accepted", [])
                if write:
                    target = ROOT / ".plugin" / "skills" / skill_name / "SKILL.md"
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(text)
                    return f"wrote {target.relative_to(ROOT)} (piecewise on the atomic tier; all laws hold)"
                return text
            _record("skill", skill_name, f"{_model_of(tiny)}+piecewise", "refused", failures)

        _record("skill", skill_name, "host-agent", "handoff", [])
        return _handoff(skill_name, pkg)

    from .stubs import draft_skill, revise_skill

    surface = package_surface(pkg)
    shape = duck_shape()
    laws = STRUCTURAL + GROUNDING + (tools_exist(surface),)

    text = draft_skill(session, package_surface=surface, duck_shape=shape,
                       house_rules=HOUSE_RULES, skill_name=skill_name,
                       description_of_users="non-technical marketers working through an agent")
    text = _with_provenance(text, "draft_skill", session, fingerprint(surface))

    failures = _check(text, laws)
    if failures:
        text = revise_skill(session, draft=text, failures=failures)
        text = _with_provenance(text, "draft_skill+revise", session, fingerprint(surface))
        failures = _check(text, laws)
    if failures:
        _record("skill", skill_name, _model_of(session), "refused", failures)
        return "REFUSED — the generation could not satisfy its laws:\n  " + "\n  ".join(failures)
    _record("skill", skill_name, _model_of(session), "accepted", [])

    target = ROOT / ".plugin" / "skills" / skill_name / "SKILL.md"
    if write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        return f"wrote {target.relative_to(ROOT)} ({len(text)} chars, all laws hold)"
    return text


def _assemble_piecewise(session, skill_name: str, pkg: str) -> tuple[str, list[str]]:
    """Structure from code, prose from atomic slots. Returns (text, failures)."""
    import yaml

    from .stubs import describe_skill, tool_method

    surface = package_surface(pkg)
    shape = duck_shape()
    from .stubs import describe_skill, tool_method

    specs = tuple((s.__doc__ or "") for s in (describe_skill, tool_method))
    laws = STRUCTURAL + GROUNDING + (tools_exist(surface), substance(surface, specs))
    fns = [f for f in surface["functions"] if not f.get("infra")]

    desc = str(describe_skill(
        session, skill_name=skill_name,
        tool_names=[f["name"] for f in fns], tool_docs=[f["doc"] for f in fns],
    )).strip().replace("\n", " ")
    sections = []
    for f in fns:
        # one retry per piece: atomic-sized revision is within the tier's
        # floor, and a piece that stays filler fails the substance law below
        para = ""
        for _attempt in range(2):
            para = " ".join(str(tool_method(
                session, tool_signature=f["signature"], tool_doc=f["doc"],
                skill_name=skill_name,
            )).split()).strip()
            low, doc = para.lower(), f["doc"].strip().lower()
            from .laws import echoes as _echoes

            if len(para.split()) >= 10 and low != f["name"] \
                    and not (doc and (low in doc or doc in low)) \
                    and not any(_echoes(para, s) for s in specs):
                break
        sections.append(f"## `{f['name']}`\n\n`{f['signature']}`\n\n{para}")

    fm = yaml.safe_dump({"name": skill_name, "description": desc},
                        sort_keys=False, allow_unicode=True, width=1000).strip()
    header = _provenance("piecewise", session, fingerprint(surface))
    rules = "\n".join(f"- {r}" for r in HOUSE_RULES)
    text = (f"---\n{fm}\n---\n\n{header}\n\n# {skill_name}\n\n"
            + "\n\n".join(sections)
            + f"\n\n## Rules\n\n{rules}\n")
    return text, _check(text, laws)


def _handoff(skill_name: str, pkg: str) -> str:
    """The grounded task for the host agent — same facts, same laws, same
    refusal contract the stubs get; the drafter differs, the gate does not."""
    import json

    surface = package_surface(pkg)
    shape = duck_shape()
    laws = STRUCTURAL + GROUNDING + (tools_exist(surface),)
    spec = {
        "task": f"Write skills/{skill_name}/SKILL.md as a complete Agent Skills std skill.",
        "contract": (
            "YAML frontmatter (name: exactly the skill name; description: one dense "
            "sentence — what the tools cover and WHEN to use the skill), then a body "
            "teaching an agent the METHOD: which function answers which marketing "
            "question, in what order, with what caveats. Name ONLY functions in "
            "package_surface and ONLY env vars appearing in its docs. Where duck_shape "
            "shows real tables, teach joining results against them. End with "
            "house_rules verbatim under '## Rules'. Include, directly after the "
            "frontmatter fence: <!-- GENERATED by monty gen (host-agent) "
            f"instruments=sha256:{fingerprint(surface)} -->"
        ),
        "package_surface": surface,
        "duck_shape": shape,
        "house_rules": HOUSE_RULES,
        "laws": [f"{law.name}: {law.description}" for law in laws],
        "then": "Run `monty gen lint` — a FAIL line means fix and rerun; the build gate is the enforcement.",
    }
    return (
        "NO LOCAL MODEL — HANDING THE DRAFT TO YOU, THE HOST AGENT.\n"
        "Fulfill this task exactly; the laws are checked deterministically after.\n\n"
        + json.dumps(spec, indent=1)
    )


def _with_provenance(text: str, stub: str, session, print_hash: str) -> str:
    """Provenance right after the frontmatter fence — fence must stay first."""
    fm, body = parse_frontmatter(text)
    header = _provenance(stub, session, print_hash)
    if fm:
        import yaml

        fm_text = yaml.safe_dump(fm, sort_keys=False, allow_unicode=True).strip()
        return f"---\n{fm_text}\n---\n\n{header}\n\n{body.strip()}\n"
    return f"{header}\n\n{text.strip()}\n"


def gen_word(name: str, context: str = "") -> str:
    """Propose one ontology word, law-checked; appending stays a human act."""
    from montology_ontology import check as onto_check, connect

    # THE TINY TIER: a one-line definition is atomic-stub work, exactly what
    # a 270M-500M model can hold — the combination-of-tiny-SLMs idea, scoped
    # to where the capability floor allows it. Bodies never route here.
    session = tiny_session() or gen_session()
    if isinstance(session, str):
        return session

    from .stubs import define_word

    existing = [r["name"] for r in connect(readonly=True).execute("SELECT name FROM word")] \
        if (ROOT / "ontology" / "data" / "ontology.db").exists() else []
    laws = word_laws(onto_check)

    try:
        line = define_word(session, name=name,
                           usage_context=context or f"the montology workspace, package surfaces mentioning {name}",
                           existing_words=existing)
    except Exception as e:  # noqa: BLE001
        _record("word", name, _model_of(session), "errored", [type(e).__name__])
        return (f"the model could not produce a definition ({type(e).__name__}). "
                "Repair: retry, or define it yourself with `monty onto add`.")
    failures = _check(line, laws)
    if failures:
        _record("word", name, _model_of(session), "refused", failures)
        return "REFUSED — the definition could not satisfy its laws:\n  " + "\n  ".join(failures)
    _record("word", name, _model_of(session), "accepted", [])
    return (f"{line.strip()}\n\n(accept it with: monty onto add "
            f"\"{name}\" \"<the definition above>\" — gen proposes, you commit)")


